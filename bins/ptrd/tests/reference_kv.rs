//! Starts the real `ptrd` binary with `--backend reference-kv` and talks HTTP to it.

use std::io::{Read, Write};
use std::net::{TcpListener, TcpStream};
use std::process::{Child, Command, Stdio};
use std::time::{Duration, Instant};

struct Daemon {
    child: Child,
    addr: String,
    dir: std::path::PathBuf,
}

impl Drop for Daemon {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
        let _ = std::fs::remove_dir_all(&self.dir);
    }
}

/// On unix `ptrd` creates its sampling keys itself; elsewhere a missing key is a startup error
/// by design (see `load_or_create_key` in `src/main.rs`), so the test provisions fixed,
/// non-secret test keys the way an operator would before starting the daemon.
#[cfg(not(unix))]
fn provision_keys(data_dir: &std::path::Path) {
    std::fs::create_dir_all(data_dir).unwrap();
    for (file, byte) in [
        ("router-sampling.key", 0x5a_u8),
        ("vcw-sampling.key", 0xa5_u8),
    ] {
        let path = data_dir.join(file);
        if !path.exists() {
            std::fs::write(&path, [byte; 32]).unwrap();
        }
    }
}

fn command(dir: &std::path::Path, addr: &str, backend: &str) -> Command {
    let config = concat!(env!("CARGO_MANIFEST_DIR"), "/../../config/default.toml");
    #[cfg(not(unix))]
    provision_keys(dir);
    let mut command = Command::new(env!("CARGO_BIN_EXE_ptrd"));
    command
        .env("PTR_CONFIG", config)
        .args(["--bind", addr, "--backend", backend, "--data-dir"])
        .arg(dir)
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    command
}

fn temp_dir(tag: &str) -> std::path::PathBuf {
    let dir = std::env::temp_dir().join(format!("ptrd-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn free_addr() -> String {
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    listener.local_addr().unwrap().to_string()
}

fn start(backend: &str) -> Daemon {
    let dir = temp_dir(backend);
    let addr = free_addr();
    let child = command(&dir, &addr, backend).spawn().unwrap();
    let daemon = Daemon { child, addr, dir };
    let deadline = Instant::now() + Duration::from_secs(60);
    while Instant::now() < deadline {
        if http(&daemon.addr, "GET", "/health", "").is_some() {
            return daemon;
        }
        std::thread::sleep(Duration::from_millis(100));
    }
    panic!("ptrd did not come up");
}

/// (status, lowercased header block, body)
fn http(addr: &str, method: &str, path: &str, body: &str) -> Option<(u16, String, String)> {
    let mut stream = TcpStream::connect(addr).ok()?;
    stream
        .set_read_timeout(Some(Duration::from_secs(30)))
        .ok()?;
    let request = format!(
        "{method} {path} HTTP/1.1\r\nhost: {addr}\r\ncontent-type: application/json\r\n\
         content-length: {}\r\nconnection: close\r\n\r\n{body}",
        body.len()
    );
    stream.write_all(request.as_bytes()).ok()?;
    let mut raw = String::new();
    stream.read_to_string(&mut raw).ok()?;
    let (head, body) = raw.split_once("\r\n\r\n")?;
    let status = head.split_whitespace().nth(1)?.parse().ok()?;
    Some((status, head.to_lowercase(), body.to_owned()))
}

fn hit_tokens(head: &str) -> usize {
    head.lines()
        .find_map(|line| line.strip_prefix("x-ptr-kv-hit-tokens:"))
        .expect("hit-tokens header")
        .trim()
        .parse()
        .unwrap()
}

#[test]
fn reference_kv_reuses_a_shared_prefix_across_requests() {
    let daemon = start("reference-kv");
    let prefix = "shared system prompt of well over thirty-two tokens: ";
    assert!(prefix.len() >= 32);
    let mut answers = Vec::new();
    for (id, tail) in [("a", "first question"), ("b", "second question")] {
        let text = format!("{prefix}{tail}");
        let body = format!(r#"{{"id":"{id}","text":"{text}"}}"#);
        let (status, head, body) = http(&daemon.addr, "POST", "/v1/requests", &body).unwrap();
        assert_eq!(status, 200, "{body}");
        answers.push((head, serde_like_text(&body)));
    }
    assert_eq!(hit_tokens(&answers[0].0), 0, "cold first request");
    assert!(
        hit_tokens(&answers[1].0) > 0,
        "second request reuses the prefix"
    );
    // Same shape: both answers carry a non-empty generated byte text.
    assert!(!answers[0].1.is_empty() && !answers[1].1.is_empty());
}

/// The `"text":"..."` field of the response body, without a JSON dependency.
fn serde_like_text(body: &str) -> String {
    let start = body.find(r#""text":""#).expect("text field") + 8;
    let rest = &body[start..];
    rest[..rest.find('"').unwrap_or(rest.len())].to_owned()
}

#[test]
fn unknown_backend_names_are_still_refused() {
    let dir = temp_dir("unknown");
    let status = command(&dir, &free_addr(), "no-such-backend")
        .status()
        .unwrap();
    let _ = std::fs::remove_dir_all(&dir);
    assert_eq!(status.code(), Some(2));
}
